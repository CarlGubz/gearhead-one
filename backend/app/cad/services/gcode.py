"""G-code post-processors (Fanuc-style, LinuxCNC, GRBL) for the CAM event stream."""
from __future__ import annotations

import math
from datetime import datetime, timezone

DEFAULT_POST = {
    "dialect": "fanuc",  # fanuc | linuxcnc | grbl
    "program_name": "CADWEB",
    "program_number": 1001,
    "line_numbers": False,
    "work_offset": "G54",
    "coolant": "M8",  # "" for none
    "safe_height": 25.0,  # tool-change height above stock top
    "clearance": 3.0,  # retract plane above stock top
    "decimals": 3,
}

DIALECTS = {
    "fanuc": {"canned": True, "tool_change": True, "tlc": True, "percent": True},
    "linuxcnc": {"canned": True, "tool_change": True, "tlc": True, "percent": False},
    "grbl": {"canned": False, "tool_change": False, "tlc": False, "percent": False},
}


def post_process(events: list[dict], tools: dict, ops_by_id: dict, post: dict, stock) -> str:
    cfg = {**DEFAULT_POST, **(post or {})}
    dia = DIALECTS.get(cfg["dialect"], DIALECTS["fanuc"])
    dec = int(cfg["decimals"])
    out: list[str] = []
    n = [10]

    def fmt(v: float) -> str:
        s = f"{v:.{dec}f}".rstrip("0").rstrip(".")
        return "0" if s in ("-0", "") else s

    def emit(line: str):
        if cfg["line_numbers"] and line and not line.startswith(("%", "(", "O")):
            out.append(f"N{n[0]} {line}")
            n[0] += 10
        else:
            out.append(line)

    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    if dia["percent"]:
        out.append("%")
        out.append(f"O{int(cfg['program_number']):04d} ({str(cfg['program_name']).upper()[:40]})")
    else:
        out.append(f"({cfg['program_name']})")
    out.append(f"(GENERATED BY CADWEB CAM {now})")
    out.append(
        f"(STOCK X{fmt(stock.xmin)}..{fmt(stock.xmax)} Y{fmt(stock.ymin)}..{fmt(stock.ymax)} Z{fmt(stock.zmin)}..{fmt(stock.zmax)})"
    )
    seen = []
    for e in events:
        if e["t"] == "tool" and e["tool"]["id"] not in seen:
            seen.append(e["tool"]["id"])
            t = e["tool"]
            out.append(f"(T{t['id']} {t.get('name', '')} D{fmt(t['diameter'])} {t.get('type', '')})")
    emit("G90 G94 G17 G21" + (" G40 G49 G80" if dia["tlc"] else ""))
    emit(cfg["work_offset"])

    pos = {"x": None, "y": None, "z": None}
    last_feed = [None]
    modal = [None]  # last G motion code
    in_canned = [False]
    cur_tool: dict = {}
    z_clear = stock.zmax + float(cfg["clearance"])

    def axes(x=None, y=None, z=None) -> str:
        parts = []
        for name, v in (("x", x), ("y", y), ("z", z)):
            if v is None:
                continue
            if pos[name] is None or abs(pos[name] - v) > 10 ** -(dec + 1):
                parts.append(f"{name.upper()}{fmt(v)}")
            pos[name] = v
        return " ".join(parts)

    def end_canned():
        if in_canned[0]:
            emit("G80")
            in_canned[0] = False
            modal[0] = None
            pos["z"] = None

    for e in events:
        if e["t"] == "tool":
            end_canned()
            t = e["tool"]
            cur_tool = t
            emit("M5")
            if cfg["coolant"]:
                emit("M9")
            out.append(f"(TOOL {t['id']}: {t.get('name', '')})")
            if dia["tool_change"]:
                emit(f"T{t['id']} M6")
                if dia["tlc"]:
                    emit(f"G43 H{t['id']}")
            else:
                emit("M0 (CHANGE TOOL AND PRESS CYCLE START)")
            emit(f"S{int(t.get('rpm', 10000))} M3")
            if cfg["coolant"]:
                emit(cfg["coolant"])
            last_feed[0] = None
            modal[0] = None
            continue

        tool = tools.get(e.get("tool"), cur_tool or {})
        op = ops_by_id.get(e.get("op"), {})
        params = op.get("params", {}) if op else {}

        if e["t"] == "drill":
            feed = float(params.get("feed") or 0) or float(tool.get("plunge_feed") or tool.get("feed") or 200)
            r_plane = e["z_top"] + 2.0
            if dia["canned"]:
                if not in_canned[0]:
                    if pos["z"] is None or pos["z"] < z_clear - 1e-6:
                        emit(f"G0 Z{fmt(z_clear)}")
                        pos["z"] = z_clear
                code = "G83" if e["peck"] > 0 else ("G82" if e["dwell"] > 0 else "G81")
                parts = [f"G99 {code}", f"X{fmt(e['x'])}", f"Y{fmt(e['y'])}", f"Z{fmt(e['z_bottom'])}", f"R{fmt(r_plane)}"]
                if e["peck"] > 0:
                    parts.append(f"Q{fmt(e['peck'])}")
                if e["dwell"] > 0 and code == "G82":
                    parts.append(f"P{fmt(e['dwell'])}")
                parts.append(f"F{fmt(feed)}")
                emit(" ".join(parts))
                in_canned[0] = True
                pos["x"], pos["y"] = e["x"], e["y"]
            else:  # expanded cycle (GRBL has no canned cycles)
                if pos["z"] is None or abs(pos["z"] - z_clear) > 1e-6:
                    emit(f"G0 Z{fmt(z_clear)}")
                emit(f"G0 X{fmt(e['x'])} Y{fmt(e['y'])}")
                emit(f"G0 Z{fmt(r_plane)}")
                depth_now = e["z_top"]
                peck = e["peck"] if e["peck"] > 0 else (e["z_top"] - e["z_bottom"])
                while depth_now > e["z_bottom"] + 1e-9:
                    nxt = max(depth_now - peck, e["z_bottom"])
                    emit(f"G1 Z{fmt(nxt)} F{fmt(feed)}")
                    if nxt > e["z_bottom"] + 1e-9:
                        emit(f"G0 Z{fmt(r_plane)}")
                        emit(f"G0 Z{fmt(nxt + 0.5)}")
                    depth_now = nxt
                if e["dwell"] > 0:
                    emit(f"G4 P{fmt(e['dwell'])}")
                emit(f"G0 Z{fmt(z_clear)}")
                pos.update({"x": e["x"], "y": e["y"], "z": z_clear})
                modal[0] = "G0"
            continue

        # linear moves
        end_canned()
        k = e["k"]
        if k == "rapid":
            body = axes(e["x"], e["y"], e["z"])
            if not body:
                continue
            emit(("G0 " if modal[0] != "G0" else "") + body)
            modal[0] = "G0"
        else:
            f = float(params.get("plunge_feed") or 0) or float(tool.get("plunge_feed") or tool.get("feed") or 300) if k == "plunge" else (
                float(params.get("feed") or 0) or float(tool.get("feed") or 600)
            )
            body = axes(e["x"], e["y"], e["z"])
            if not body:
                continue
            word = ("G1 " if modal[0] != "G1" else "") + body
            if last_feed[0] is None or abs(last_feed[0] - f) > 1e-9:
                word += f" F{fmt(f)}"
                last_feed[0] = f
            emit(word)
            modal[0] = "G1"

    end_canned()
    emit("M5")
    if cfg["coolant"]:
        emit("M9")
    emit(f"G0 Z{fmt(stock.zmax + float(cfg['safe_height']))}")
    if dia["tlc"]:
        emit("G49")
    emit("G0 X0 Y0" if cfg["dialect"] == "grbl" else "G0 X0 Y0")
    emit("M30")
    if dia["percent"]:
        out.append("%")
    return "\n".join(out) + "\n"

def read_internal(path: Path, n: int):
    """internalField of an OpenFOAM field file as an array of length n (scalar) or (n, 3) (vector)."""
    from foamlib import FoamFieldFile

    val = FoamFieldFile(path).internal_field
    arr = np.asarray(val, dtype=float)
    if arr.ndim == 0:
        return np.full(n, float(arr))
    if arr.ndim == 1 and arr.shape[0] == 3 and n != 3:
        return np.tile(arr, (n, 1))
    return arr


def time_dirs(case_dir: Path) -> list[tuple[float, Path]]:
    out = []
    for p in Path(case_dir).iterdir():
        if p.is_dir():
            try:
                out.append((float(p.name), p))
            except ValueError:
                pass
    return sorted(out)


class _Mapper:
    """Maps OpenFOAM cells (via their centres) onto the structured CFDFlow grid."""

    def __init__(self, ofc: OpenFOAMCase, case_dir: Path):
        self.ofc = ofc
        C = read_internal(Path(case_dir) / "0" / "C", 0)
        self.ncell = C.shape[0]
        n, h = ofc.n, ofc.h
        self.idx = tuple(np.clip(np.floor(C[:, a] / h[a]).astype(int), 0, n[a] - 1) for a in range(3))
        self.solid = np.ones(n, bool)
        self.solid[self.idx] = False

    def to_grid(self, values: np.ndarray) -> np.ndarray:
        out = np.zeros(self.ofc.n)
        out[self.idx] = values
        return out


def read_time(ofc: OpenFOAMCase, mapper: _Mapper, tdir: Path) -> dict[str, np.ndarray]:
    nd = ofc.nd
    n = mapper.ncell
    U = read_internal(tdir / "U", n)
    f = {"u": mapper.to_grid(U[:, 0]), "v": mapper.to_grid(U[:, 1]), "w": mapper.to_grid(U[:, 2]) if nd == 3 else np.zeros(ofc.n)}
    f["p"] = mapper.to_grid((read_internal(tdir / ofc.p_name, n) - ofc.p_ref) * ofc.p_scale)
    if ofc.energy and (tdir / "T").exists():
        f["T"] = mapper.to_grid(read_internal(tdir / "T", n))
    else:
        f["T"] = np.full(ofc.n, ofc.case.initial.temperature)
    if nd == 2:
        f = {k: v[:, :, 0] for k, v in f.items()}
    return f


def _last_line(path: Path) -> list[str] | None:
    try:
        with open(path, "rb") as fh:
            fh.seek(0, 2)
            size = fh.tell()
            fh.seek(max(0, size - 8192))
            lines = [ln for ln in fh.read().decode("utf-8", "replace").splitlines() if ln.strip() and not ln.startswith("#")]
        return lines[-1].replace("(", " ").replace(")", " ").split() if lines else None
    except OSError:
        return None


def _post_file(case_dir: Path, fo: str, name: str) -> Path | None:
    base = Path(case_dir) / "postProcessing" / fo
    if not base.exists():
        return None
    cands = sorted(base.glob(f"*/{name}"), key=lambda p: p.stat().st_mtime)
    return cands[-1] if cands else None


def read_probes(ofc: OpenFOAMCase, case_dir: Path) -> dict[str, float]:
    vals: dict[str, float] = {}
    if not ofc.case.probes:
        return vals
    U = _post_file(case_dir, "probes", "U")
    row = _last_line(U) if U else None
    if row:
        for i, pr in enumerate(ofc.case.probes):
            comps = row[1 + 3 * i: 4 + 3 * i]
            if len(comps) == 3:
                for c, val in zip("uvw"[: ofc.nd], comps):
                    vals[f"{pr.id}.{c}"] = float(val)
    for name, key, scale, shift in ((ofc.p_name, "p", ofc.p_scale, ofc.p_ref),
                                    ("T", "T", 1.0, 0.0)):
        if key == "T" and not ofc.energy:
            continue
        pf = _post_file(case_dir, "probes", name)
        row = _last_line(pf) if pf else None
        if row:
            for i, pr in enumerate(ofc.case.probes):
                if 1 + i < len(row):
                    vals[f"{pr.id}.{key}"] = (float(row[1 + i]) - shift) * scale
    return vals


def read_forces(ofc: OpenFOAMCase, case_dir: Path) -> dict[str, dict]:
    out = {}
    per_depth = ofc.L[2] if ofc.nd == 2 else 1.0
    q_by_patch = {}
    if ofc.compressible:
        hf = _post_file(case_dir, "wallHeatFlux", "wallHeatFlux.dat")
        if hf:
            for ln in hf.read_text(errors="replace").splitlines():
                parts = ln.split()
                if len(parts) >= 5 and not ln.startswith("#"):
                    q_by_patch[parts[1]] = float(parts[4])
    for pn, ob in ofc.obstacles:
        f = _post_file(case_dir, f"forces_{pn}", "force.dat")
        row = _last_line(f) if f else None
        if not row or len(row) < 4:
            continue
        fx, fy, fz = (float(v) / per_depth for v in row[1:4])
        d = {"Fx": fx, "Fy": fy, "Q": q_by_patch.get(pn, 0.0) / per_depth}
        if ofc.nd == 3:
            d["Fz"] = fz
        out[ob.id] = d
    return out



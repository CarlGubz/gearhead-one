"""OpenFOAM backend: writes a complete OpenFOAM case from the CFDFlow case, runs it and reads the
result back onto the structured CFDFlow grid.

Case generation
---------------
* ``blockMesh``: one hex block ``nx x ny x nz`` (2-D: one cell thick with ``empty`` front/back).
  The six sides become patches named ``left right bottom top back front``; every obstacle gets an
  (initially empty) wall patch ``obs_<id>``.
* Obstacles: for each obstacle ``topoSet`` selects the cells to keep (``boxToCell`` /
  ``cylinderToCell`` / ``sphereToCell`` + ``invert``) and ``subsetMesh -overwrite -patch obs_<id>``
  removes the solid cells, putting the exposed faces into the obstacle patch. Same "cell centre
  inside the shape" rule as the native solvers, so the meshes are identical.
* Solver selected from the physics:

  ================================  =====================  ======================
  physics                           steady                 transient
  ================================  =====================  ======================
  isothermal (laminar or RANS)      ``simpleFoam``         ``pimpleFoam``
  forced convection (energy only)   ``simpleFoam`` + T     ``pimpleFoam`` + T
  natural / mixed convection        ``buoyantBoussinesq``  ``buoyantBoussinesq``
                                    ``SimpleFoam``         ``PimpleFoam``
  ================================  =====================  ======================

  Forced convection solves the temperature as a passive scalar with the ``scalarTransport``
  function object (constant properties - the same model as the native solver; SIMPLEC keeps it
  robust). Buoyant cases use the true Boussinesq solvers (density constant except in the gravity
  term - again the native model). ``CFD_OPENFOAM_BUOYANT_SOLVER=compressible`` switches to
  ``buoyantSimpleFoam`` / ``buoyantPimpleFoam`` with ``heRhoThermo`` and the ``Boussinesq``
  equation of state, which keeps the density variation in every term (only equivalent when
  beta * dT << 1). Heat sources become ``scalarSemiImplicitSource`` fvOptions (on ``h`` in W/m3,
  or on ``T`` in K/s).
* Turbulence: laminar, ``kEpsilon`` or ``kOmegaSST`` with standard wall functions; inlet values
  from 5 % intensity and a mixing length of 0.07 hydraulic diameters.
* Function objects: ``probes`` (CFDFlow probes), ``forces`` per obstacle, ``wallHeatFlux``.
* Parabolic inlets use ESI's ``exprFixedValue`` boundary condition (``6 s (1 - s)`` per
  tangential direction, mean = the inlet speed).

Written for the ESI/OpenCFD distribution (``openfoam.com``, v2306+; tested with v2406). The
``Allrun`` script in the case directory runs everything and can be used outside CFDFlow.
"""

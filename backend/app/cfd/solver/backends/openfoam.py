class OpenFOAMBackend(SolverBackend):
    id = "openfoam"
    label = "OpenFOAM"
    description = ("Generates and runs a full OpenFOAM case (blockMesh + topoSet/subsetMesh; simpleFoam / pimpleFoam, "
                   "+ scalarTransport for forced convection, buoyantBoussinesqSimpleFoam / PimpleFoam for buoyancy; laminar, "
                   "k-epsilon or k-omega SST). Runs natively, in Docker or WSL; falls back to the native Python solver when "
                   "OpenFOAM is unavailable.")
    capabilities = {"dims": (2, 3), "steady": True, "transient": True, "energy": True, "buoyancy": True, "turbulence": True}
    fallback_id = "native"
    exportable = True

    def _launcher(self):
        s = get_settings()
        return resolve_launcher("openfoam", lambda: shutil.which("simpleFoam") is not None, "simpleFoam",
                                s.openfoam_docker_image, s.openfoam_launcher, s.openfoam_docker_image, s.openfoam_wsl_distro)

    def availability(self) -> Availability:
        return self._launcher()[1]

    def check(self, case) -> list[CheckMsg]:
        out = super().check(case)
        if case.models.buoyancy and case.models.energy and case.models.turbulence != "laminar":
            out.append(CheckMsg("info", "models", "Buoyant RANS uses compressible::alphatWallFunction (Prt = 0.85) on walls."))
        if any(getattr(case.boundaries, s).type == "inlet" and getattr(case.boundaries, s).profile == "parabolic"
               for s in case.sides()):
            out.append(CheckMsg("info", "boundaries", "OpenFOAM: parabolic inlets use exprFixedValue (OpenFOAM.com v2306 or newer)."))
        return out

    @staticmethod
    def make_case(case) -> OpenFOAMCase:
        return OpenFOAMCase(case, get_settings().openfoam_buoyant_solver)

    def export_case(self, case, dest: Path) -> list[Path]:
        return self.make_case(case).write(dest)

    def run(self, case, hooks, run_dir: Path) -> BackendResult:
        launcher, av = self._launcher()
        if launcher is None:
            raise BackendFailed(f"OpenFOAM is not available: {av.detail}")
        ofc = self.make_case(case)
        case_dir = Path(run_dir) / "openfoam"
        if case_dir.exists():
            shutil.rmtree(case_dir, ignore_errors=True)
        ofc.write(case_dir)
        hooks.log("info", f"OpenFOAM case written to {case_dir} ({ofc.solver}, {av.detail}).")
        hooks.log("info", f"Mesh: {' x '.join(str(k) for k in ofc.n[: ofc.nd])} cells"
                          f"{' (one cell thick, empty front/back)' if ofc.nd == 2 else ''}, "
                          f"{len(ofc.obstacles)} obstacle patch(es), turbulence: {ofc.turb}")
        name = f"cfdflow-{Path(run_dir).name[:12]}-{int(time.time()) % 100000}"
        cmd = launcher.command(case_dir, ["bash", "Allrun"], name)
        g = build_grid_nd(case)
        tracker = ProgressTracker(case)
        state = {"time": 0.0, "it": 0, "res": {}, "converged": False, "failed": None, "fatal": [], "step": "",
                 "last_prog": 0.0, "last_snap": 0.0, "snap_time": None}
        mapper_box: dict = {}

        def emit():
            res = state["res"]
            if not res:
                return
            vals = read_probes(ofc, case_dir)
            vals["dt"] = state.get("dt", 0.0)
            for oid, d in read_forces(ofc, case_dir).items():
                for k, v in d.items():
                    if k != "Q" or ofc.compressible:
                        vals[f"{oid}.{k}"] = v
            hooks.on_monitor(state["it"], state["time"], dict(res), vals)

        def maybe_snapshot():
            if "m" not in mapper_box:
                if not (case_dir / "0" / "C").exists():
                    return
                try:
                    mapper_box["m"] = _Mapper(ofc, case_dir)
                except Exception:  # noqa: BLE001 - not written completely yet
                    return
            td = [t for t in time_dirs(case_dir) if t[0] > 0 and (t[1] / "U").exists()]
            if not td or td[-1][0] == state["snap_time"]:
                return
            t, p = td[-1]
            try:
                f = read_time(ofc, mapper_box["m"], p)
            except Exception:  # noqa: BLE001 - directory still being written
                return
            state["snap_time"] = t
            hooks.save_latest(meta_for(case, g, self.id, state["it"]), mapper_box["m"].solid.reshape(g.n), t, frame_from_cc(g, f))

        time_re = re.compile(r"^Time = ([-+0-9.eE]+)")
        res_re = re.compile(r"Solving for (\w+), Initial residual = ([-+0-9.eE]+)")
        dt_re = re.compile(r"^deltaT = ([-+0-9.eE]+)")

        def on_lines(lines):
            for ln in lines:
                s = ln.strip()
                m = time_re.match(s)
                if m:
                    emit()
                    state["time"] = float(m.group(1))
                    state["it"] += 1
                    state["res"] = {}
                    continue
                m = res_re.search(s)
                if m:
                    key = RES_NAMES.get(m.group(1))
                    if key and key not in state["res"]:
                        state["res"][key] = float(m.group(2))
                    continue
                m = dt_re.match(s)
                if m:
                    state["dt"] = float(m.group(1))
                if s.startswith("CFDFLOW-STEP"):
                    state["step"] = s.split(maxsplit=1)[1]
                    hooks.log("info", f"OpenFOAM: {state['step']} …")
                elif s.startswith("CFDFLOW-FAILED"):
                    state["failed"] = s.split(maxsplit=1)[1]
                elif "solution converged in" in s or "reached convergence criteria" in s:
                    state["converged"] = True
                    hooks.log("info", f"OpenFOAM: {s}")
                elif "FOAM FATAL" in s or state["fatal"]:
                    if len(state["fatal"]) < 25:
                        state["fatal"].append(s)
            now = time.time()
            if now - state["last_prog"] > 0.4:
                r = max([v for k, v in state["res"].items() if k in ("u", "v", "w", "p", "T")] or [0.0])
                hooks.on_progress(tracker.fraction(state["it"], state["time"], r or None), state["it"], state["time"])
                state["last_prog"] = now
            if now - state["last_snap"] > 3.0 and state["it"] > 0:
                state["last_snap"] = now
                maybe_snapshot()

        def graceful_stop():
            hooks.log("warning", "Stop requested: asking OpenFOAM to write the current solution and stop (stopAt writeNow).")
            cd = case_dir / "system" / "controlDict"
            txt = cd.read_text(encoding="utf-8")
            with open(cd, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(re.sub(r"stopAt\s+\w+;", "stopAt          writeNow;", txt, count=1))

        t0 = time.time()
        rc, stopped = run_streaming(cmd, case_dir, Path(run_dir) / "openfoam.log", on_lines=on_lines,
                                    should_stop=hooks.should_stop, on_stop=graceful_stop,
                                    kill=lambda p: launcher.kill(p, name), grace=30.0)
        emit()
        wall = time.time() - t0
        if state["failed"] or (rc != 0 and not stopped):
            detail = " ".join(state["fatal"][:12]) or f"exit code {rc}"
            raise BackendFailed(f"OpenFOAM step '{state['failed'] or state['step']}' failed: {detail} "
                                f"(see openfoam/log.* in the run directory)")
        mapper = _Mapper(ofc, case_dir)
        tds = [t for t in time_dirs(case_dir) if (t[1] / "U").exists()]
        if not tds:
            raise BackendFailed("OpenFOAM finished without writing any results.")
        if case.run.mode == "steady":
            tds = tds[-1:]
        times, frames, last = [], [], None
        for t, p in tds:
            last = read_time(ofc, mapper, p)
            times.append(t)
            frames.append(frame_from_cc(g, last))
        solid = mapper.solid.reshape(g.n)
        g.solid[...] = solid
        fields = full_fields(g, last)
        notes = []
        converged = state["converged"] or (case.run.mode == "transient" and times[-1] >= case.run.end_time * (1 - 1e-6))
        if case.run.mode == "steady" and not converged and not stopped:
            notes.append(f"Iteration limit ({case.run.max_iterations}) reached before the residual targets.")
        loads = read_forces(ofc, case_dir) or None
        if loads and ofc.energy and not ofc.compressible:  # no wallHeatFlux: heat rates from the staircase surface
            m = case.material
            uc = [fields["u"], fields["v"]] + ([fields["w"]] if g.ndim == 3 else [])
            stair = obstacle_loads_cc(g, case.obstacles, fields["p"], uc, fields["T"], m.viscosity, m.conductivity, True)
            for oid, d in loads.items():
                d["Q"] = stair.get(oid, {}).get("Q", 0.0)
        summary = summary_from_cc(case, g, fields, iterations=state["it"], sim_time=times[-1], wall=wall,
                                  converged=converged, notes=notes, backend=self.id, loads=loads)
        summary["openfoam"] = {"solver": ofc.solver, "launcher": av.mode, "case_dir": "openfoam/"}
        hooks.log("info" if not stopped else "warning",
                  f"OpenFOAM {'stopped' if stopped else 'finished'} after {state['it']} steps, t={times[-1]:.4g}, wall {wall:.1f} s"
                  + (" (converged)" if converged else ""))
        meta = meta_for(case, g, self.id, state["it"])
        return BackendResult("cancelled" if stopped else "completed", converged, state["it"], times[-1], meta, solid,
                             times, frames, summary)


def monitors_for_result(case, g, fields):  # pragma: no cover - convenience for notebooks
    return monitors_from_cc(case, g, fields)

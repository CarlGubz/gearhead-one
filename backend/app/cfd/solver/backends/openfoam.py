INWARD = {"left": (1, 0, 0), "right": (-1, 0, 0), "bottom": (0, 1, 0), "top": (0, -1, 0), "back": (0, 0, 1), "front": (0, 0, -1)}
TANGENT_VEC = {"left": (0, 1, 0), "right": (0, 1, 0), "bottom": (1, 0, 0), "top": (1, 0, 0), "back": (1, 0, 0), "front": (1, 0, 0)}
P_REF = 1.0e5  # absolute reference pressure of the buoyant (compressible-form) solvers
RES_NAMES = {"Ux": "u", "Uy": "v", "Uz": "w", "p": "p", "p_rgh": "p", "h": "T", "T": "T", "k": "k",
             "epsilon": "epsilon", "omega": "omega"}


def patch_name(oid: str) -> str:
    return "obs_" + re.sub(r"[^A-Za-z0-9_]", "_", oid)


def _v(v) -> str:
    return "(" + " ".join(f"{float(x):.10g}" for x in v) + ")"


def _header(cls: str, obj: str, location: str | None = None) -> str:
    loc = f'    location    "{location}";\n' if location else ""
    return ("/*--------------------------------*- C++ -*----------------------------------*\\\n"
            "  Generated by CFDFlow - https://github.com/ (OpenFOAM case export)\n"
            "\\*---------------------------------------------------------------------------*/\n"
            f"FoamFile\n{{\n    version     2.0;\n    format      ascii;\n    class       {cls};\n{loc}    object      {obj};\n}}\n\n")


class OpenFOAMCase:
    """Pure case generator (no OpenFOAM needed). ``write(dest)`` produces a runnable case."""

    def __init__(self, case, buoyant_form: str = "boussinesq"):
        self.case = case
        self.nd = case.ndim
        d, m = case.domain, case.mesh
        self.n = (m.nx, m.ny, m.nz if self.nd == 3 else 1)
        self.h2 = (d.width / m.nx, d.height / m.ny)
        thin = min(self.h2)
        self.L = (d.width, d.height, d.depth if self.nd == 3 else thin)
        self.h = tuple(l / k for l, k in zip(self.L, self.n))
        self.energy = case.models.energy
        self.buoyant = self.energy and case.models.buoyancy  # Boussinesq solver family
        self.scalar_T = self.energy and not self.buoyant  # passive temperature (scalarTransport)
        self.turb = case.models.turbulence
        self.steady = case.run.mode == "steady"
        self.sides = {s: getattr(case.boundaries, s) for s in ("left", "right", "bottom", "top", "back", "front")}
        self.obstacles = [(patch_name(o.id), o) for o in case.obstacles]
        self.compressible = self.buoyant and buoyant_form == "compressible"
        self.bouss = self.buoyant and not self.compressible
        self.p_name = "p_rgh" if self.buoyant else "p"
        self.p_ref = P_REF if self.compressible else 0.0  # absolute level of the compressible-form solvers
        self.p_scale = 1.0 if self.compressible else case.material.density  # kinematic -> Pa
        self.t_eqn = "h" if self.compressible else "T"

    # ------------------------------------------------------------------ helpers
    @property
    def solver(self) -> str:
        if self.compressible:
            return "buoyantSimpleFoam" if self.steady else "buoyantPimpleFoam"
        if self.bouss:
            return "buoyantBoussinesqSimpleFoam" if self.steady else "buoyantBoussinesqPimpleFoam"
        return "simpleFoam" if self.steady else "pimpleFoam"

    def side_kind(self, side: str) -> str:
        if self.nd == 2 and side in ("back", "front"):
            return "empty"
        return self.sides[side].type

    def _u_ref(self) -> float:
        bcs = [self.sides[s] for s in self.sides if self.side_kind(s) != "empty"]
        speeds = [b.velocity for b in bcs if b.type == "inlet"] + [abs(b.wall_velocity) for b in bcs if b.type == "wall"]
        if speeds and max(speeds) > 0:
            return max(speeds)
        ini = self.case.initial
        return max(abs(ini.velocity_x), abs(ini.velocity_y), abs(ini.velocity_z), 1e-3)

    def _hydraulic_diameter(self, side: str) -> float:
        axis = next(a for a, pair in enumerate(AXIS_SIDES) if side in pair)
        dims = [self.L[a] for a in range(self.nd) if a != axis]
        if len(dims) == 1:
            return 2 * dims[0] if self.nd == 2 else dims[0]
        return 4 * dims[0] * dims[1] / (2 * (dims[0] + dims[1]))

    def _turb_inlet(self, side: str | None) -> dict:
        U = self.sides[side].velocity if side else self._u_ref()
        Dh = self._hydraulic_diameter(side) if side else min(self.L[: self.nd])
        k = 1.5 * (0.05 * max(U, 1e-6)) ** 2
        lm = 0.07 * Dh
        cmu = 0.09
        return {"k": k, "epsilon": cmu**0.75 * k**1.5 / lm, "omega": math.sqrt(k) / (cmu**0.25 * lm)}

    def _probe_points(self) -> list[tuple]:
        pts = []
        for pr in self.case.probes:
            p = probe_point(pr, self.nd, self.case.domain.depth)
            pts.append(p if self.nd == 3 else (p[0], p[1], self.L[2] / 2))
        return pts

    # ------------------------------------------------------------------ system/
    def block_mesh(self) -> str:
        lx, ly, lz = self.L
        nx, ny, nz = self.n
        faces = {"left": "(0 4 7 3)", "right": "(1 2 6 5)", "bottom": "(0 1 5 4)", "top": "(3 7 6 2)",
                 "back": "(0 3 2 1)", "front": "(4 5 6 7)"}
        ptype = {"wall": "wall", "inlet": "patch", "outlet": "patch", "symmetry": "symmetry", "empty": "empty"}
        bnd = "".join(f"    {s}\n    {{\n        type {ptype[self.side_kind(s)]};\n        faces ({faces[s]});\n    }}\n"
                      for s in faces)
        bnd += "".join(f"    {pn}\n    {{\n        type wall;\n        faces ();\n    }}\n" for pn, _ in self.obstacles)
        return (_header("dictionary", "blockMeshDict") + "scale 1;\n\nvertices\n(\n"
                f"    (0 0 0) ({lx:.10g} 0 0) ({lx:.10g} {ly:.10g} 0) (0 {ly:.10g} 0)\n"
                f"    (0 0 {lz:.10g}) ({lx:.10g} 0 {lz:.10g}) ({lx:.10g} {ly:.10g} {lz:.10g}) (0 {ly:.10g} {lz:.10g})\n);\n\n"
                f"blocks\n(\n    hex (0 1 2 3 4 5 6 7) ({nx} {ny} {nz}) simpleGrading (1 1 1)\n);\n\nedges ();\n\n"
                f"boundary\n(\n{bnd});\n")

    def _mesh_source(self, ob) -> str:
        """Imported solid: the cells CFDFlow marks solid, as a union of boxes on cell faces.

        Geometric (not cell labels) because every obstacle runs its own `subsetMesh`, which renumbers the cells.
        """
        from ..meshsolid import solid_runs_boxes

        g = build_grid_nd(self.case)
        k = next(i for i, o in enumerate(self.case.obstacles) if o.id == ob.id)
        mask = g.solid_id == k
        if self.nd == 2:
            mask = mask[:, :, None]
        h = (self.h[0], self.h[1], self.h[2])
        boxes = solid_runs_boxes(mask, h)
        if self.nd == 2:
            boxes = [((lo[0], lo[1], -self.L[2]), (hi[0], hi[1], 2 * self.L[2])) for lo, hi in boxes]
        if not boxes:  # not resolved by the mesh: select nothing
            boxes = [((-2 * self.L[0], -2 * self.L[1], -2 * self.L[2]), (-self.L[0], -self.L[1], -self.L[2]))]
        body = " ".join(f"({_v(lo)} {_v(hi)})" for lo, hi in boxes)
        return f"source boxToCell; boxes ({body});"

    def _source(self, ob) -> str:
        lz = self.L[2]
        depth = self.case.domain.depth
        if ob.shape == "mesh":
            return self._mesh_source(ob)
        if self.nd == 3 and ob.shape == "sphere":
            zc = ob.z if ob.z is not None else depth / 2
            return f"source sphereToCell; origin {_v((ob.x, ob.y, zc))}; radius {ob.radius:.10g};"
        if self.nd == 3:
            zc, hz = z_span(ob, depth)
            z0, z1 = max(zc - hz, -lz), min(zc + hz, 2 * lz)
        else:
            z0, z1 = -lz, 2 * lz
        if ob.shape == "rectangle":
            lo, hi = obstacle_bounds(ob, 2, depth)
            return f"source boxToCell; box {_v((lo[0], lo[1], z0))} {_v((hi[0], hi[1], z1))};"
        return (f"source cylinderToCell; point1 {_v((ob.x, ob.y, z0))}; point2 {_v((ob.x, ob.y, z1))}; "
                f"radius {ob.radius:.10g};")

    def topo_set_obstacle(self, pn: str, ob) -> str:
        return (_header("dictionary", "topoSetDict") + "actions\n(\n"
                f"    {{ name keep_{pn}; type cellSet; action new; {self._source(ob)} }}\n"
                f"    {{ name keep_{pn}; type cellSet; action invert; }}\n);\n")

    def topo_set_sources(self) -> str:
        lz, depth = self.L[2], self.case.domain.depth
        acts = []
        for hs in self.case.heat_sources:
            if self.nd == 3:
                zc, hz = z_span(hs, depth)
                z0, z1 = zc - hz, zc + hz
            else:
                z0, z1 = -lz, 2 * lz
            lo = (hs.x - hs.width / 2, hs.y - hs.height / 2, z0)
            hi = (hs.x + hs.width / 2, hs.y + hs.height / 2, z1)
            acts.append(f"    {{ name {self._src_name(hs)}; type cellSet; action new; source boxToCell; box {_v(lo)} {_v(hi)}; }}\n")
        return _header("dictionary", "topoSetDict") + "actions\n(\n" + "".join(acts) + ");\n"

    def control_dict(self) -> str:
        rs = self.case.run
        if self.steady:
            end, dt = rs.max_iterations, 1
            write = f"writeControl    timeStep;\nwriteInterval   {max(50, min(500, rs.max_iterations // 20 or 1))};\npurgeWrite      2;\n"
            adjust = ""
        else:
            end = rs.end_time
            u = self._u_ref()
            dt = rs.fixed_dt or rs.cfl * min(self.h[: self.nd]) / max(u, 1e-9)
            nfr = max(rs.snapshot_count - 1, 1)
            write = f"writeControl    adjustableRunTime;\nwriteInterval   {end / nfr:.10g};\npurgeWrite      0;\n"
            adjust = ("adjustTimeStep  no;\n" if rs.fixed_dt else
                      f"adjustTimeStep  yes;\nmaxCo           {rs.cfl:.6g};\nmaxDeltaT       {end / 20:.10g};\n")
        fields = ["U", self.p_name] + (["T"] if self.energy else [])
        funcs = ""
        pts = self._probe_points()
        if pts:
            funcs += ("    probes\n    {\n        type            probes;\n        libs            (sampling);\n"
                      "        writeControl    timeStep;\n        writeInterval   1;\n"
                      f"        fields          ({' '.join(fields)});\n"
                      "        probeLocations\n        (\n" + "".join(f"            {_v(p)}\n" for p in pts) + "        );\n    }\n")
        for pn, _ in self.obstacles:
            rho = "        rho             rho;\n        pRef            %.10g;\n" % P_REF if self.compressible else \
                f"        rho             rhoInf;\n        rhoInf          {self.case.material.density:.10g};\n"
            funcs += (f"    forces_{pn}\n    {{\n        type            forces;\n        libs            (forces);\n"
                      f"        writeControl    timeStep;\n        writeInterval   1;\n        patches         ({pn});\n"
                      f"{rho}        CofR            (0 0 0);\n        log             false;\n    }}\n")
        if self.scalar_T:
            funcs += self._scalar_transport()
        if self.compressible and self.obstacles:
            funcs += ("    wallHeatFlux\n    {\n        type            wallHeatFlux;\n        libs            (fieldFunctionObjects);\n"
                      "        writeControl    writeTime;\n        patches         (\"obs_.*\");\n        log             false;\n    }\n")
        return (_header("dictionary", "controlDict") +
                f"application     {self.solver};\nstartFrom       startTime;\nstartTime       0;\nstopAt          endTime;\n"
                f"endTime         {end:.10g};\ndeltaT          {dt:.10g};\n{write}{adjust}writeFormat     ascii;\n"
                "writePrecision  10;\nwriteCompression off;\ntimeFormat      general;\ntimePrecision   8;\n"
                f"runTimeModifiable true;\n\nfunctions\n{{\n{funcs}}}\n")

    def _scalar_transport(self) -> str:
        m = self.case.material
        alpha = m.conductivity / (m.density * m.specific_heat)
        src = ""
        if self.case.heat_sources:
            src = "        fvOptions\n        {\n" + "".join(
                f"            {self._src_name(hs)}\n            {{\n                type            scalarSemiImplicitSource;\n"
                f"                selectionMode   cellSet;\n                cellSet         {self._src_name(hs)};\n"
                f"                volumeMode      specific;\n                sources\n                {{\n"
                f"                    T               ({hs.power_density / (m.density * m.specific_heat):.10g} 0);\n"
                "                }\n            }\n" for hs in self.case.heat_sources) + "        }\n"
        return ("    T\n    {\n        type            scalarTransport;\n        libs            (solverFunctionObjects);\n"
                f"        field           T;\n        D               {alpha:.10g};\n        schemesField    T;\n"
                "        bounded01       false;\n        nCorr           1;\n        resetOnStartUp  false;\n"
                f"        writeControl    writeTime;\n{src}    }}\n")

    def fv_schemes(self) -> str:
        bounded = "bounded " if self.steady else ""
        conv = "linearUpwind grad(U)"
        if self.compressible:
            divs = (f"    div(phi,U)      {bounded}Gauss {conv};\n    div(phi,h)      {bounded}Gauss upwind;\n"
                    f"    div(phi,e)      {bounded}Gauss upwind;\n    div(phi,K)      {bounded}Gauss upwind;\n"
                    f"    div(phi,Ekp)    {bounded}Gauss upwind;\n"
                    "    div(((rho*nuEff)*dev2(T(grad(U))))) Gauss linear;\n")
        else:
            divs = f"    div(phi,U)      {bounded}Gauss {conv};\n    div((nuEff*dev2(T(grad(U))))) Gauss linear;\n"
        if self.energy and not self.compressible:
            divs += f"    div(phi,T)      {bounded}Gauss limitedLinear 1;\n"
        divs += f"    div(phi,k)      {bounded}Gauss upwind;\n    div(phi,epsilon) {bounded}Gauss upwind;\n" \
                f"    div(phi,omega)  {bounded}Gauss upwind;\n"
        ddt = "steadyState" if self.steady else "Euler"
        return (_header("dictionary", "fvSchemes") +
                f"ddtSchemes\n{{\n    default         {ddt};\n}}\n\ngradSchemes\n{{\n    default         Gauss linear;\n}}\n\n"
                f"divSchemes\n{{\n    default         none;\n{divs}}}\n\n"
                "laplacianSchemes\n{\n    default         Gauss linear corrected;\n}\n\n"
                "interpolationSchemes\n{\n    default         linear;\n}\n\nsnGradSchemes\n{\n    default         corrected;\n}\n\n"
                "wallDist\n{\n    method          meshWave;\n}\n")

    def _residual_targets(self) -> tuple[float, float]:
        f = self.case.run.tolerance / 1e-5
        return min(max(1e-4 * f, 1e-8), 1e-2), min(max(1e-5 * f, 1e-9), 1e-3)

    def fv_solution(self) -> str:
        p = self.p_name
        rp, ru = self._residual_targets()
        prefv = self.p_ref
        eqs = "U|k|epsilon|omega" + ("|h|e" if self.compressible else "") + ("|T" if self.energy and not self.compressible else "")
        solvers = (f"    {p}\n    {{\n        solver          GAMG;\n        smoother        GaussSeidel;\n"
                   f"        tolerance       1e-8;\n        relTol          {0.05 if self.steady else 0.01};\n    }}\n"
                   f"    {p}Final\n    {{\n        $" + p + ";\n        relTol          0;\n    }\n"
                   f"    \"({eqs})\"\n    {{\n        solver          smoothSolver;\n        smoother        symGaussSeidel;\n"
                   "        tolerance       1e-9;\n        relTol          0.1;\n    }\n"
                   f"    \"({eqs})Final\"\n    {{\n        $U;\n        relTol          0;\n    }}\n")
        if self.compressible:
            solvers += "    \"rho.*\"\n    {\n        solver          PCG;\n        preconditioner  DIC;\n        tolerance       0;\n        relTol          0;\n    }\n"
        turbres = "        \"(k|epsilon|omega)\" %g;\n" % ru if self.turb != "laminar" else ""
        if self.steady:
            hres = f"        {self.t_eqn}               {ru:g};\n" if self.buoyant else ""
            algo = (f"SIMPLE\n{{\n    nNonOrthogonalCorrectors 0;\n    consistent      {'no' if self.buoyant else 'yes'};\n"
                    f"    momentumPredictor {'no' if self.buoyant else 'yes'};\n"
                    f"    pRefCell        0;\n    pRefValue       {prefv:g};\n"
                    f"    residualControl\n    {{\n        {p}             {rp:g};\n        U               {ru:g};\n{hres}{turbres}    }}\n}}\n\n")
            if self.buoyant:
                relax = ("relaxationFactors\n{\n    fields\n    {\n        rho             1.0;\n        p_rgh           0.7;\n    }\n"
                         f"    equations\n    {{\n        U               0.3;\n        {self.t_eqn}               {0.3 if self.compressible else 0.5};\n"
                         "        \".*\"            0.7;\n    }\n}\n")
            else:
                relax = "relaxationFactors\n{\n    equations\n    {\n        U               0.9;\n        \".*\"            0.9;\n    }\n}\n"
        else:
            algo = (f"PIMPLE\n{{\n    momentumPredictor yes;\n    nOuterCorrectors 1;\n    nCorrectors     2;\n"
                    f"    nNonOrthogonalCorrectors 0;\n    pRefCell        0;\n    pRefValue       {prefv:g};\n}}\n\n")
            relax = "relaxationFactors\n{\n    equations\n    {\n        \".*\"            1;\n    }\n}\n"
        return _header("dictionary", "fvSolution") + f"solvers\n{{\n{solvers}}}\n\n" + algo + relax

    def decompose_par(self) -> str:
        return _header("dictionary", "decomposeParDict") + \
            f"numberOfSubdomains {self.case.solver.processes};\n\nmethod          scotch;\n"

    @staticmethod
    def _src_name(hs) -> str:
        return "src_" + patch_name(hs.id)[4:]

    def fv_options(self) -> str:
        body = ""
        m = self.case.material
        for hs in self.case.heat_sources:
            nm = self._src_name(hs)
            val = hs.power_density if self.compressible else hs.power_density / (m.density * m.specific_heat)
            body += (f"{nm}\n{{\n    type            scalarSemiImplicitSource;\n    selectionMode   cellSet;\n"
                     f"    cellSet         {nm};\n    volumeMode      specific;\n    sources\n    {{\n"
                     f"        {self.t_eqn}               ({val:.10g} 0);\n    }}\n}}\n\n")
        return _header("dictionary", "fvOptions") + body

    # ------------------------------------------------------------------ constant/
    def transport_properties(self) -> str:
        m = self.case.material
        out = _header("dictionary", "transportProperties") + \
            f"transportModel  Newtonian;\n\nnu              {m.viscosity / m.density:.10g};\n"
        if self.bouss:
            out += (f"beta            {m.thermal_expansion:.10g};\nTRef            {self.case.models.reference_temperature:.10g};\n"
                    f"Pr              {m.viscosity * m.specific_heat / m.conductivity:.10g};\nPrt             0.85;\n")
        return out

    def turbulence_properties(self, obj="turbulenceProperties") -> str:
        if self.turb == "laminar":
            return _header("dictionary", obj) + "simulationType  laminar;\n"
        model = {"k_epsilon": "kEpsilon", "k_omega_sst": "kOmegaSST"}[self.turb]
        return _header("dictionary", obj) + \
            f"simulationType  RAS;\n\nRAS\n{{\n    RASModel        {model};\n    model           {model};\n" \
            "    turbulence      on;\n    printCoeffs     off;\n}\n"

    def thermophysical_properties(self) -> str:
        m, mo = self.case.material, self.case.models
        beta = m.thermal_expansion if mo.buoyancy else 0.0
        pr = m.viscosity * m.specific_heat / m.conductivity
        return (_header("dictionary", "thermophysicalProperties") +
                "thermoType\n{\n    type            heRhoThermo;\n    mixture         pureMixture;\n    transport       const;\n"
                "    thermo          hConst;\n    equationOfState Boussinesq;\n    specie          specie;\n"
                "    energy          sensibleEnthalpy;\n}\n\nmixture\n{\n    specie\n    {\n        molWeight       28.96;\n    }\n"
                f"    equationOfState\n    {{\n        rho0            {m.density:.10g};\n        T0              {mo.reference_temperature:.10g};\n"
                f"        beta            {beta:.10g};\n    }}\n    thermodynamics\n    {{\n        Cp              {m.specific_heat:.10g};\n"
                f"        Hf              0;\n    }}\n    transport\n    {{\n        mu              {m.viscosity:.10g};\n"
                f"        Pr              {pr:.10g};\n    }}\n}}\n")

    def gravity(self) -> str:
        mo = self.case.models
        g = (mo.gravity_x, mo.gravity_y, mo.gravity_z if self.nd == 3 else 0.0) if mo.buoyancy else (0.0, 0.0, 0.0)
        return _header("uniformDimensionedVectorField", "g", "constant") + f"dimensions      [0 1 -2 0 0 0 0];\nvalue           {_v(g)};\n"

    # ------------------------------------------------------------------ 0/
    def _inlet_velocity(self, side: str) -> str:
        bc = self.sides[side]
        nrm = INWARD[side]
        if bc.profile != "parabolic":
            return f"type            fixedValue;\n        value           uniform {_v(tuple(bc.velocity * c for c in nrm))};"
        axis = next(a for a, pair in enumerate(AXIS_SIDES) if side in pair)
        terms = []
        for a in range(self.nd):
            if a == axis:
                continue
            c = "xyz"[a]
            terms.append(f"6*(pos().{c}()/{self.L[a]:.10g})*(1-pos().{c}()/{self.L[a]:.10g})")
        prof = f"{bc.velocity:.10g}*" + "*".join(terms)
        comp = [f"{nrm[i]}*{prof}" if nrm[i] else "0" for i in range(3)]
        return (f"type            exprFixedValue;\n        value           uniform {_v(tuple(bc.velocity * c for c in nrm))};\n"
                f"        valueExpr       \"vector({', '.join(comp)})\";")

    def _patch_entries(self, field: str) -> dict[str, str]:
        """Boundary entries of ``field`` for every patch."""
        out = {}
        mo = self.case.models
        T0 = self.case.initial.temperature
        for side in self.sides:
            kind = self.side_kind(side)
            bc = self.sides[side]
            if kind in ("empty", "symmetry"):
                out[side] = f"type            {kind};"
                continue
            out[side] = self._entry(field, kind, bc, T0, side)
        for pn, ob in self.obstacles:
            out[pn] = self._entry(field, "obstacle", ob, T0, None)
        return out

    def _entry(self, field, kind, bc, T0, side) -> str:
        wall = kind in ("wall", "obstacle")
        if field == "U":
            if kind == "inlet":
                return self._inlet_velocity(side)
            if kind == "outlet":
                return "type            zeroGradient;"
            if kind == "wall" and bc.wall_velocity != 0:
                return f"type            fixedValue;\n        value           uniform {_v(tuple(bc.wall_velocity * c for c in TANGENT_VEC[side]))};"
            return "type            noSlip;"
        if field == "p":
            if self.buoyant:
                return "type            calculated;\n        value           uniform %g;" % self.p_ref
            return "type            fixedValue;\n        value           uniform 0;" if kind == "outlet" else "type            zeroGradient;"
        if field == "p_rgh":
            if kind == "outlet":
                return "type            fixedValue;\n        value           uniform %g;" % self.p_ref
            return "type            fixedFluxPressure;\n        value           uniform %g;" % self.p_ref
        if field == "T":
            if kind == "inlet":
                return f"type            fixedValue;\n        value           uniform {bc.temperature:.10g};"
            if kind == "outlet":
                return f"type            inletOutlet;\n        inletValue      uniform {T0:.10g};\n        value           uniform {T0:.10g};"
            if wall and bc.thermal == "fixed":
                return f"type            fixedValue;\n        value           uniform {bc.temperature:.10g};"
            return "type            zeroGradient;"
        if field == "alphat":
            if wall and self.turb != "laminar" and self.bouss:
                return "type            alphatJayatillekeWallFunction;\n        Prt             0.85;\n        value           uniform 0;"
            if wall and self.turb != "laminar":
                return "type            compressible::alphatWallFunction;\n        Prt             0.85;\n        value           uniform 0;"
            return "type            calculated;\n        value           uniform 0;"
        if field == "nut":
            if wall:
                return "type            nutkWallFunction;\n        value           uniform 0;"
            return "type            calculated;\n        value           uniform 0;"
        # k / epsilon / omega
        tin = self._turb_inlet(side if kind == "inlet" else None)
        val = tin[field]
        if kind == "inlet":
            return f"type            fixedValue;\n        value           uniform {val:.10g};"
        if kind == "outlet":
            return f"type            inletOutlet;\n        inletValue      uniform {val:.10g};\n        value           uniform {val:.10g};"
        wf = {"k": "kqRWallFunction", "epsilon": "epsilonWallFunction", "omega": "omegaWallFunction"}[field]
        return f"type            {wf};\n        value           uniform {val:.10g};"

    def field_file(self, field: str) -> str:
        ini = self.case.initial
        spec = {
            "U": ("volVectorField", "[0 1 -1 0 0 0 0]", f"uniform {_v((ini.velocity_x, ini.velocity_y, ini.velocity_z if self.nd == 3 else 0))}"),
            "p": ("volScalarField", "[1 -1 -2 0 0 0 0]" if self.compressible else "[0 2 -2 0 0 0 0]", f"uniform {self.p_ref:g}"),
            "p_rgh": ("volScalarField", "[1 -1 -2 0 0 0 0]" if self.compressible else "[0 2 -2 0 0 0 0]", f"uniform {self.p_ref:g}"),
            "T": ("volScalarField", "[0 0 0 1 0 0 0]", f"uniform {ini.temperature:.10g}"),
            "alphat": ("volScalarField", "[1 -1 -1 0 0 0 0]" if self.compressible else "[0 2 -1 0 0 0 0]", "uniform 0"),
            "nut": ("volScalarField", "[0 2 -1 0 0 0 0]", "uniform 0"),
            "k": ("volScalarField", "[0 2 -2 0 0 0 0]", f"uniform {self._turb_inlet(None)['k']:.10g}"),
            "epsilon": ("volScalarField", "[0 2 -3 0 0 0 0]", f"uniform {self._turb_inlet(None)['epsilon']:.10g}"),
            "omega": ("volScalarField", "[0 0 -1 0 0 0 0]", f"uniform {self._turb_inlet(None)['omega']:.10g}"),
        }[field]
        entries = self._patch_entries(field)
        bf = "".join(f"    {name}\n    {{\n        {body}\n    }}\n" for name, body in entries.items())
        return _header(spec[0], field, "0") + f"dimensions      {spec[1]};\n\ninternalField   {spec[2]};\n\nboundaryField\n{{\n{bf}}}\n"

    def field_names(self) -> list[str]:
        f = ["U", "p"]
        if self.buoyant:
            f += ["p_rgh", "T", "alphat"]
        elif self.scalar_T:
            f += ["T"]
        if self.turb != "laminar":
            f += ["nut", "k", "epsilon" if self.turb == "k_epsilon" else "omega"]
        return f

    # ------------------------------------------------------------------ Allrun
    def allrun(self) -> str:
        np_ = self.case.solver.processes
        lines = [
            "#!/bin/bash",
            "# Generated by CFDFlow: meshes and runs this OpenFOAM case.  Usage: ./Allrun",
            'cd "$(dirname "$0")" || exit 1',
            'if [ -z "$WM_PROJECT_DIR" ]; then',
            '  for f in /usr/lib/openfoam/openfoam*/etc/bashrc /opt/openfoam*/etc/bashrc "$HOME"/OpenFOAM/OpenFOAM-*/etc/bashrc; do',
            '    if [ -f "$f" ]; then . "$f"; break; fi',
            "  done",
            "fi",
            "export OMPI_ALLOW_RUN_AS_ROOT=1 OMPI_ALLOW_RUN_AS_ROOT_CONFIRM=1",
            'step() { name="$1"; shift; echo "CFDFLOW-STEP $name"; "$@" > "log.$name" 2>&1 || '
            '{ echo "CFDFLOW-FAILED $name"; tail -n 60 "log.$name"; exit 1; }; }',
            "rm -rf 0 constant/polyMesh processor* postProcessing",
            "find . -maxdepth 1 -type d -regex './[0-9.eE+-]+' ! -name 0.orig -exec rm -rf {} +",
            "step blockMesh blockMesh",
        ]
        for pn, _ in self.obstacles:
            lines.append(f"step topoSet.{pn} topoSet -dict system/topoSetDict.{pn}")
            lines.append(f"step subsetMesh.{pn} subsetMesh -overwrite keep_{pn} -patch {pn}")
        if self.energy and self.case.heat_sources:
            lines.append("step topoSet.sources topoSet -dict system/topoSetDict.sources")
        lines += [
            "step checkMesh checkMesh",
            "cp -r 0.orig 0",
            "step writeCellCentres postProcess -func writeCellCentres -time 0",
            "set -o pipefail",
            f'echo "CFDFLOW-STEP {self.solver}"',
        ]
        if np_ > 1:
            lines += ["step decomposePar decomposePar -force",
                      f"mpirun -np {np_} {self.solver} -parallel 2>&1 | tee log.{self.solver} || {{ echo CFDFLOW-FAILED {self.solver}; exit 1; }}",
                      "step reconstructPar reconstructPar"]
        else:
            lines.append(f"{self.solver} 2>&1 | tee log.{self.solver} || {{ echo CFDFLOW-FAILED {self.solver}; exit 1; }}")
        lines.append('echo "CFDFLOW-DONE"')
        return "\n".join(lines) + "\n"

    # ------------------------------------------------------------------ write
    def write(self, dest: Path) -> list[Path]:
        dest = Path(dest)
        files: dict[str, str] = {
            "system/blockMeshDict": self.block_mesh(),
            "system/controlDict": self.control_dict(),
            "system/fvSchemes": self.fv_schemes(),
            "system/fvSolution": self.fv_solution(),
            "constant/turbulenceProperties": self.turbulence_properties(),
            "constant/momentumTransport": self.turbulence_properties("momentumTransport"),
            "Allrun": self.allrun(),
        }
        for pn, ob in self.obstacles:
            files[f"system/topoSetDict.{pn}"] = self.topo_set_obstacle(pn, ob)
        if self.case.solver.processes > 1:
            files["system/decomposeParDict"] = self.decompose_par()
        if self.compressible:
            files["constant/thermophysicalProperties"] = self.thermophysical_properties()
        else:
            files["constant/transportProperties"] = self.transport_properties()
        if self.buoyant:
            files["constant/g"] = self.gravity()
            if self.case.heat_sources:
                files["system/fvOptions"] = self.fv_options()
        if self.energy and self.case.heat_sources:
            files["system/topoSetDict.sources"] = self.topo_set_sources()
        for f in self.field_names():
            files[f"0.orig/{f}"] = self.field_file(f)
        written = []
        for rel, text in files.items():
            p = dest / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            with open(p, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
            written.append(p)
        (dest / "case.foam").touch()
        try:
            (dest / "Allrun").chmod(0o755)
        except OSError:
            pass
        return written


